"""Generate version constants from RELEASE.json; --check never writes files."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def sync(root=ROOT, check=False):
    release = json.loads((root / 'RELEASE.json').read_text(encoding='utf-8'))
    version, build, release_id = (release[k] for k in ('version', 'build_number', 'release_id'))
    if (not re.fullmatch(r'\d+\.\d+\.\d+', version) or type(build) is not int
            or not 1 <= build <= 2100000000
            or not re.fullmatch(r'\d{4}-\d{2}-\d{2}-R\d+', release_id)):
        raise ValueError('Invalid RELEASE.json')
    full = f'{version}+{build}'
    label = f'{full} · {release_id}'
    info = dict(release, full_version=full, label=label)
    outputs = {
        'server/backend/app/build_info.py': '# Generated by tools/sync_version.py.\nBUILD_INFO = ' + repr(info) + '\n',
        'shared/flutter_core/lib/build_info.dart': (
            '// Generated by tools/sync_version.py.\n'
            'abstract final class SadohodBuild {\n'
            f"  static const version = '{version}';\n"
            f'  static const buildNumber = {build};\n'
            f"  static const releaseId = '{release_id}';\n"
            f"  static const fullVersion = '{full}';\n"
            f"  static const label = '{label}';\n"
            '}\n'),
        'server/preview/build_info.js': '// Generated by tools/sync_version.py.\nwindow.SADOHOD_BUILD = Object.freeze(' + json.dumps(info, ensure_ascii=False) + ');\n',
    }
    for name in ('buyer_app/pubspec.yaml', 'seller_app/pubspec.yaml', 'shared/flutter_core/pubspec.yaml'):
        source = (root / name).read_text(encoding='utf-8')
        if len(re.findall(r'^version:.*$', source, re.M)) != 1:
            raise ValueError(f'Expected one version in {name}')
        outputs[name] = re.sub(r'^version:.*$', 'version: ' + full, source, flags=re.M)
    stale = [name for name, data in outputs.items()
             if not (root / name).exists() or (root / name).read_text(encoding='utf-8') != data]
    if check and stale:
        raise ValueError('Version files are out of sync: ' + ', '.join(stale))
    if not check:
        for name, data in outputs.items():
            (root / name).parent.mkdir(parents=True, exist_ok=True)
            (root / name).write_text(data, encoding='utf-8')
    return label


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    print(sync(check=args.check))
